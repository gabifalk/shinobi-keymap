# Derived lookup tables.

KEYCODES: dict[str, int] = {}
for _kc, _name, _hi, _lo, _layouts in _PHYSICAL_KEYS:
    KEYCODES[_name] = _kc
for _kc, _name in _ACTION_KEYS:
    KEYCODES[_name] = _kc

KEYCODE_TO_NAME: dict[int, str] = {kc: name for name, kc in KEYCODES.items()}

MATRIX_TO_KEYCODE: dict[str, dict[tuple[int, int], int]] = {layout: {} for layout in LAYOUTS}
KEYCODE_TO_MATRIX: dict[str, dict[int, tuple[int, int]]] = {layout: {} for layout in LAYOUTS}
for _kc, _name, _hi, _lo, _layouts in _PHYSICAL_KEYS:
    for _layout in _layouts:
        MATRIX_TO_KEYCODE[_layout][(_hi, _lo)] = _kc
        KEYCODE_TO_MATRIX[_layout][_kc] = (_hi, _lo)

PHYSICAL_KEYCODES: set[int] = {kc for kc, _, _, _, _ in _PHYSICAL_KEYS}
